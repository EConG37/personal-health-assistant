/* Package original PNGs as small alpha-preserving WebP sprites; no visual edits. */
const {app,BrowserWindow}=require('electron');
const fs=require('node:fs'),path=require('node:path');
const ingredientArt=require('../desktop/ui/food-art'),dishArt=require('../desktop/ui/dish-art');
const atlases=[...ingredientArt.atlases,...dishArt.atlases];
const root=path.join(__dirname,'..'),dir=path.join(root,'desktop/ui/assets');
app.disableHardwareAcceleration();
app.whenReady().then(async()=>{
 const win=new BrowserWindow({show:false,webPreferences:{sandbox:true,contextIsolation:true}});
 try{
  await win.loadURL('about:blank');
  const rules=['/* Generated by scripts/build-food-art.js from food-art.js. */'];
  let originalBytes=0,webpBytes=0;
  for(const atlas of atlases){
   const source=fs.readFileSync(path.join(dir,atlas.file+'.png'));originalBytes+=source.length;
   for(const density of [1,2]){
    const side=atlas.columns*96*density;
    const data=await win.webContents.executeJavaScript(`(async()=>{
     const img=new Image();img.src=${JSON.stringify('data:image/png;base64,'+source.toString('base64'))};await img.decode();
     const canvas=document.createElement('canvas');canvas.width=canvas.height=${side};
     const ctx=canvas.getContext('2d');ctx.imageSmoothingQuality='high';ctx.drawImage(img,0,0,${side},${side});
     return canvas.toDataURL('image/webp',.94);
    })()`);
    if(!data.startsWith('data:image/webp;base64,'))throw Error('WebP encoding unavailable');
    const bytes=Buffer.from(data.split(',')[1],'base64');webpBytes+=bytes.length;
    fs.writeFileSync(path.join(dir,atlas.file+(density===2?'@2x':'')+'.webp'),bytes);
   }
   const url=`assets/${atlas.file}`;
   rules.push(`.food-sprite.food-atlas-${atlas.name}{background-image:url('${url}.png');background-image:image-set(url('${url}.webp') type('image/webp') 1x,url('${url}@2x.webp') type('image/webp') 2x,url('${url}.png') type('image/png') 2x);background-size:${atlas.columns*100}% ${atlas.columns*100}%;background-repeat:no-repeat${atlas.file.endsWith('-v2')?';clip-path:inset(7% 5% 1%)':''}}`);
   atlas.ids.forEach((id,index)=>rules.push(`.food-id-${id}{background-position:${index%atlas.columns/(atlas.columns-1)*100}% ${Math.floor(index/atlas.columns)/(atlas.columns-1)*100}%}`));
  }
  rules.push('.meal-art>.food-art.staple-art{left:auto;top:auto;right:0;bottom:0;width:43px;height:43px;filter:drop-shadow(0 2px 2px #23372012)}',
   '.card-front>.meal-art>.food-art.staple-art{width:42px;height:42px}',
   '.dish{display:flex;align-items:center;gap:9px}.dish>.dish-picture{width:34px;height:34px;flex:none}.dish>.nm{flex:1;min-width:0;overflow-wrap:anywhere}.dish>.qty{flex:none;white-space:nowrap}',
   '@container(max-width:95px){.card-front>.meal-art>.food-art.staple-art{width:38px;height:38px}}');
  fs.writeFileSync(path.join(root,'desktop/ui/food-art.css'),rules.join('\n')+'\n');
  console.log(JSON.stringify({atlases:atlases.length,ingredients:atlases.reduce((n,a)=>n+a.ids.length,0),originalBytes,webpBytes}));
  app.exit(0);
 }catch(e){console.error(e);app.exit(1);}
});
